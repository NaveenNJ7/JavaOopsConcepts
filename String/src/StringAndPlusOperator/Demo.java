package StringAndPlusOperator;

public class Demo {

	public static void main(String[] args) {
		
		// anything which we concat with String it will act as concat not as plus + operator
		System.out.println("A"+"B");
		
		System.out.println("A"+20);
		
		// with char plus will act as operator
		System.out.println('a'+'A');

	}

}
