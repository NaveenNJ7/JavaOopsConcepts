package day11_02_10;

public class Multiple {

	void m()
	{
		System.out.println("learning Methods with same name");
	}
	
	void m(int x)
	{
		System.out.println("on"+" "+x+"th "+"date");
	}
	
	void m(double x)
	{
		System.out.println(x);
	}
	
	void m(String x, int y)
	{
	 System.out.println(x+y);
	}
	
	void m(int y, String x)
	{
		System.out.println(y+x);
	}
}
