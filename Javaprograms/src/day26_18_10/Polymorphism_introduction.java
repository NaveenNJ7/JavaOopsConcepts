package day26_18_10;

public class Polymorphism_introduction {

	/*
	 
	 Method binding :
	 
	    		   Associating or mapping method caller to its method implementation or definition is called as 
	    		   
	 Polymorphism   : 
	 
	 			  1) Many forms
	 			  
	 			  2) The ability of method to behave differently when different objects are acting upon it
	 			  
	 			  3) The ability of method to exhibit different forms when different objects acting upon it
	 			  
	 Two types  : 1) Compile time polymorphism 
	 			  2) Run time polymorphism
	 
	 
	 Compile time polymorphism  : 
	 
	 			  1) It is achieved with the help of method overloading
	 			  
	 			  2) It is also referred as Early binding or static binding
	 			  
	 			  3) Method binding is happening at compile time, hence we call method overloading as Early binding, 
	 			     static binding or compile time polymorphism
	 			     
	 			  4) Out of many overload methods, which method implementation should get executed is decided by compiler
	 			     during compile time 
	 			     
	 			        
	 Run time polymorphism  :
	 
	 			  1) It is achieved with the help of 
	 			     a) Inheritance or Is-A relationship
	 			     b) Override
	 			     c) Upcasting
	 			     
	 			  2) When we call an overridden method on the superclass reference, the method implementation which gets 
	 			     executed is dependent on the subclass acting upon it.
	 			     
	 			  3) Out of many overridden method, which method implementation should get executed is decided by jvm at 
	 			     runtime.
	 			     
	 			  4) Runtime polymorphism is also called as Late binding or Dynamic binding or Dynamic methid Dispatch.
	 			  
	 Note    :    
	 			  1) If we call an overridden method on the superclass reference, always the overridden method implementation
	 			     only gets executed. 
	 			     
	 
	 */
}
