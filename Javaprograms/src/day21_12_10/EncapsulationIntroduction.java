public class EncapsulationIntroduction {
	
	
	/* 
	   Encapsulation : it is a process of wrapping or binding data members and member functions in a single entity 
	   				   called as class 
	   				   
	   				   or 
	   				   
	   				   it is a process of grouping and protecting data members and member functions in a single entity 
	   				   called as class
	   				   
	   				   
	   				   data member - nothing but variables
	   				   member functions - methods
	   				   
	   Specifications :
	   
	   			      1) class must be public non abstract 
	   			      
	   			      2) variables must be private
	   			      
	   			      3) class should have non parameterized constructor
	   			      
	   			      4) data members should have respective setter and getter method
	   			      
	   			      5) class should implement a marker interface called as Serializable
	   			      
	   			      
	  Note : 		  1) Setter method always public and non return type ( void method)
	    			  
	    			  2) Getter method public and return type
	    			  
	    			  3) if we have 5(n number) variables we should have 5 setter and 5 getter methods
	    			  
	    			  
	
	
	*/

}
