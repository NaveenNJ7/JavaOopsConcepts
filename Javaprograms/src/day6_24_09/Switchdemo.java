package day6_24_09;

public class Switchdemo {

	
	public static void main(String[] args)
	{
		
		char Grade = 'C';
		
		switch(Grade)
		
		{
			case 'A': System.out.println(" Grade is A ");
			               
			
				
			case 'B': System.out.println(" Grade is B ");
			
			               break;
			
			case 'C': System.out.println(" Grade is C ");
			
			                 break;
			                 
			default : System.out.println("Invalid"); 
			
	
		}
		
	}
}
