package Upanddown;

public class Theory {

	/*
	 
	 Upcasting - 
	     1) Creating an object of subclass and storing its address into reference of type superclass
	     2) To achieve upcasting IS-A relationship is mandatory
	     3) With superclass reference we can only access superclass properties
	     4) Upcasting will be done by implicity/automatically
	     5) superclass reference. subclass object
	     
	        ex- vehical super class, car subclass
	        
	            Vehical v = new Car(); // direct
	                      or
	            Car c = new Car();
	            Vehical v = c;
	            
	            
	  Downcasting -
	      1) The process of converting upcasted reference back to subclass type reference 
	         is called downcasting 
	      2) To achieve downcasting, upcasting is mandatory
	      3) with subclass reference we can access both superclass and subclass properties
	      4) downcasting will be done by explicitly
	     
	         syntax - (subclass name) superclass reference;
	         
	         Car c = (Car) v;
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 */
	
	
}
